#ifndef BSP_TIM_H
#define BSP_TIM_H

#include <stdint.h>

/* ============================================================================
 *  时间基准 BSP —— DWT 微秒级时间戳（不占用任何定时器/中断）
 *  ---------------------------------------------------------------------------
 *  用途：1kHz 软定时、测速窗口、零漂校准超时、调试打点。
 *  注意：32 位计数器会回绕（约 4295s），差值计算必须用无符号减法。
 * ========================================================================== */

/* 初始化：使能 DWT 计数 */
void Bsp_Time_Init(void);

/* 从上电开始的微秒时间戳（会回绕，差值用无符号减法） */
uint32_t Bsp_Time_MicroSec(void);

/* 微秒级忙等延时（>1µs 可用；极短延时建议直接 __NOP） */
void Bsp_Time_DelayUs(uint32_t us);

#endif /* BSP_TIM_H */
