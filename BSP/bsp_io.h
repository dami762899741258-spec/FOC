#ifndef BSP_IO_H
#define BSP_IO_H

#include <stdint.h>

/* ============================================================================
 *  板载 IO BSP —— 指示灯电平抽象
 *  ---------------------------------------------------------------------------
 *  LED1 = PA15（心跳灯，CubeMX 标签 LED1）
 *  LED2 = PB9 （状态灯，CubeMX 标签 LED2）
 *  只做"电平"这一层，闪烁逻辑在 bsp_led.c。
 * ========================================================================== */

/* 初始化：两个灯先灭 */
void Bsp_Io_Init(void);

/* 电平控制：on = 1 亮 / 0 灭 */
void Bsp_Io_Led1(uint8_t on);
void Bsp_Io_Led2(uint8_t on);

#endif /* BSP_IO_H */
