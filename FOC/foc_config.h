#ifndef FOC_CONFIG_H
#define FOC_CONFIG_H

#include <stdint.h>

/* ============================================================================
 *  FOC 层：参数表 + 共享数据（骨架，数值先给"保守初始值"，调试时再调）
 *  ---------------------------------------------------------------------------
 *  本文件只放"电机怎么算"的参数；硬件怎么用全在 BSP/bsp_config.h。
 *  两个时间基准（别混，PI 积分必须乘自己那个）：
 *      电流环 10kHz  → FOC_TS_I     = 100µs
 *      速度环 1kHz   → FOC_TS_SPEED = 1ms
 *  单位约定：电流 A、电压 V、角度 rad、转速 rpm、时间 s
 *
 *  ★ 骨架阶段：所有 .c 里都是空实现（TODO），参数先按样例给，填完算法后再调。
 * ========================================================================== */

/* ==========================================================================
 * 1. 时间常数
 * ========================================================================== */
#define FOC_TS_I 0.0001f      /* 电流环周期 = 1/10000 s = 100µs */
#define FOC_TS_SPEED 0.001f   /* 速度环周期 = 1/1000 s = 1ms  */

/* ==========================================================================
 * 2. 限幅（调试期先小后大）
 * ========================================================================== */
#define FOC_IQ_MAX 1.0f       /* q 轴电流上限 A（调试期先 0.3~0.5） */
#define FOC_ID_MAX 0.3f       /* d 轴电流上限 A（表贴式电机 id_ref 恒 0） */
#define FOC_RPM_MAX 2000.0f   /* 速度给定上限 rpm */
/* ★TODO: 按实测母线电压算 Vmax = 0.8 × Vbus / √3（24V → 约 11V） */
#define FOC_VMAX 9.5f

/* ==========================================================================
 * 3. 电流环 PI（d/q 各一个）
 * ========================================================================== */
#define FOC_KP_ID 1.0f        /* d 轴比例 V/A */
#define FOC_KI_ID 3000.0f     /* d 轴积分 V/(A·s) */
#define FOC_KP_IQ 1.0f        /* q 轴比例 V/A */
#define FOC_KI_IQ 3000.0f     /* q 轴积分 V/(A·s) */

/* ==========================================================================
 * 4. 速度环 PI（输出 = iq_ref）
 * ========================================================================== */
#define FOC_KP_SPD 0.005f     /* A/rpm */
#define FOC_KI_SPD 0.15f      /* A/(rpm·s) */
#define FOC_RPM_DEADBAND 3.0f /* 转速死区 rpm：误差比它小就当 0 */

/* ==========================================================================
 * 5. 对齐 ALIGN（标定电角度零点）
 * ========================================================================== */
#define FOC_ALIGN_VOLT 1.0f   /* 对齐电压 V（太大会抖/发热） */
#define FOC_ALIGN_MS 800U     /* 对齐保持时间 ms */
#define FOC_ALIGN_USE_Z 1     /* 1 = 用 Z 信号对齐；0 = 电压吸转子对齐 */
/* ★TODO: 两种方式的实现都在 foc_state.c 的 ALIGN 分支里，二选一填 */

/* ==========================================================================
 * 6. 开环 OPEN（验证功率级/相序/方向）
 * ========================================================================== */
#define FOC_OPEN_VOLT 1.0f      /* 开环电压 V */
#define FOC_OPEN_ELEC_RPM 60.0f /* 电角度转速（机械 rpm = 它 / 极对数） */

/* ==========================================================================
 * 7. 滤波系数
 * ========================================================================== */
#define FOC_SPD_LPF_ALPHA 0.2f /* 速度低通（电流一般不要滤） */

/* ==========================================================================
 * 8. 共享数据（全局一份，方便调试/VOFA 上传）
 *    各模块把中间量写进来；禁止放"只在某个函数里用"的临时变量
 * ========================================================================== */
typedef struct
{
    /* ---- 反馈量 ---- */
    float ia, ib, ic;    /* 三相电流 A */
    float ialpha, ibeta; /* Clarke 之后 A */
    float id, iq;        /* Park 之后 A */
    float theta;         /* 电角度 rad 0~2π */
    float rpm;           /* 机械转速 rpm */

    /* ---- 给定 ---- */
    float id_ref;        /* d 轴电流给定 A（一般恒 0） */
    float iq_ref;        /* q 轴电流给定 A（力矩） */
    float rpm_ref;       /* 速度给定 rpm */

    /* ---- 输出中间量 ---- */
    float vd, vq;        /* 电流环输出 V */
    float valpha, vbeta; /* 反 Park 之后 V */

    /* ---- 最终给 PWM 的占空比 0~1 ---- */
    float duty_a, duty_b, duty_c;
} FOC_t;

extern FOC_t g_foc; /* 定义在 foc_state.c */

#endif /* FOC_CONFIG_H */
